"""
Generate hayley_v3.urdf from hayley_kinematics.py + the mesh manifest written
by export_links.py.  Plain Python 3, no dependencies.

    python make_urdf.py

All link frames keep the base orientation (Z up, X forward) and sit on their
joint origin at kinematic zero, so a joint angle of 0 everywhere reproduces the
CAD/home pose, and URDF joint angles == the angles used by the Dash UI/ESP32.
Masses are rough estimates from CAD volumes (good enough for RViz/Gazebo
visualisation, not for dynamics tuning).
"""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
import sys; sys.path.insert(0, HERE)
import hayley_kinematics as hk

DESC = os.path.join(ROOT, "description")
manifest = json.load(open(os.path.join(DESC, "link_map.json")))
PKG = "package://hayley_description/meshes/"

COLORS = {
    "structure": (0.74, 0.79, 0.86, 1.0),
    "drive": (0.62, 0.63, 0.66, 1.0),
    "motor": (0.16, 0.16, 0.18, 1.0),
    "pcb": (0.10, 0.42, 0.20, 1.0),
    "hardware": (0.33, 0.33, 0.36, 1.0),
}
DENSITY = {"structure": 2.7e-6, "drive": 7.8e-6, "motor": 5.0e-6, "pcb": 1.9e-6, "hardware": 7.8e-6}  # kg/mm^3

joints, tcp = hk.home_joints()
origins = {"base_link": [0, 0, 0]}
for i, j in enumerate(joints, 1):
    origins["link%d" % i] = j["origin"]


def f(v, n=6):
    return " ".join(("%." + str(n) + "f") % (x + 0.0) for x in v)


def mat_to_rpy(R):
    # URDF rpy = fixed-axis X, Y, Z
    sy = -R[2][0]
    pitch = math.asin(max(-1, min(1, sy)))
    if abs(math.cos(pitch)) > 1e-9:
        roll = math.atan2(R[2][1], R[2][2])
        yaw = math.atan2(R[1][0], R[0][0])
    else:
        roll, yaw = math.atan2(-R[1][2], R[1][1]), 0.0
    return [roll, pitch, yaw]


# mass / COM per link from the part list
mass, com = {}, {}
for p in manifest["parts"]:
    m = p["volume_mm3"] * DENSITY[p["category"]]
    L = p["link"]
    mass[L] = mass.get(L, 0) + m
    c = com.setdefault(L, [0, 0, 0])
    for k in range(3):
        c[k] += m * p["centroid_mm"][k]

links = ["base_link"] + ["link%d" % i for i in range(1, 7)]
out = ['<?xml version="1.0"?>',
       '<!-- Project Hayley V3 (DIY-Robot-Arm-V3) - generated by digital_twin/cad_tools/make_urdf.py -->',
       '<robot name="hayley_v3">']
for cat, rgba in COLORS.items():
    out.append('  <material name="%s"><color rgba="%s"/></material>' % (cat, f(rgba, 3)))
out.append('  <link name="world"/>')
out.append('  <joint name="world_fixed" type="fixed"><parent link="world"/><child link="base_link"/>'
           '<origin xyz="0 0 0" rpy="0 0 0"/></joint>')

for L in links:
    o = origins[L]
    out.append('  <link name="%s">' % L)
    m = max(mass.get(L, 0.05), 0.05)
    c = [(com[L][k] / mass[L] if L in mass else o[k]) - o[k] for k in range(3)]
    I = 0.4 * m * 0.04 ** 2
    out.append('    <inertial><origin xyz="%s" rpy="0 0 0"/><mass value="%.4f"/>'
               '<inertia ixx="%.3e" ixy="0" ixz="0" iyy="%.3e" iyz="0" izz="%.3e"/></inertial>'
               % (f([x / 1000 for x in c]), m, I, I, I))
    for mesh in manifest["meshes"]:
        if mesh["link"] != L:
            continue
        geo = '<geometry><mesh filename="%s%s" scale="0.001 0.001 0.001"/></geometry>' % (PKG, mesh["file"])
        out.append('    <visual name="%s"><origin xyz="0 0 0" rpy="0 0 0"/>%s<material name="%s"/></visual>'
                   % (mesh["category"], geo, mesh["category"]))
        if mesh["category"] in ("structure", "motor", "drive"):
            out.append('    <collision><origin xyz="0 0 0" rpy="0 0 0"/>%s</collision>' % geo)
    out.append('  </link>')

for i, j in enumerate(joints, 1):
    parent = "base_link" if i == 1 else "link%d" % (i - 1)
    child = "link%d" % i
    rel = [(origins[child][k] - origins[parent][k]) / 1000.0 for k in range(3)]
    lo, hi = hk.LIMITS_DEG[i - 1]
    vel = math.radians(hk.JOINT_SPEED_DEG_S[i - 1])
    out.append('  <joint name="joint%d" type="revolute">' % i)
    out.append('    <parent link="%s"/><child link="%s"/>' % (parent, child))
    out.append('    <origin xyz="%s" rpy="0 0 0"/>' % f(rel))
    out.append('    <axis xyz="%s"/>' % f(j["axis"], 1))
    out.append('    <limit lower="%.5f" upper="%.5f" effort="10" velocity="%.4f"/>'
               % (math.radians(lo), math.radians(hi), vel))
    out.append('  </joint>')

# tool frame (end of the linkage table) relative to link6
R = [row[:3] for row in tcp[:3]]
p = [(tcp[k][3] - origins["link6"][k]) / 1000.0 for k in range(3)]
out.append('  <link name="tool0"/>')
out.append('  <joint name="tool0_fixed" type="fixed"><parent link="link6"/><child link="tool0"/>'
           '<origin xyz="%s" rpy="%s"/></joint>' % (f(p), f(mat_to_rpy(R))))
out.append('</robot>')

path = os.path.join(DESC, "hayley_v3.urdf")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path)
for L in links:
    print("  %-9s mass~%.2f kg" % (L, mass.get(L, 0)))

# copy URDF + meshes into the Raspberry Pi app so /twin/ can serve them
import shutil
PI_WEB = os.path.join(os.path.dirname(ROOT), "Python program loaded on Raspberry Pi 4", "twin_web", "description")
if os.path.isdir(os.path.dirname(PI_WEB)):
    # overwrite in place (deleting the folder fails while OneDrive/the server holds it open)
    shutil.copytree(DESC, PI_WEB, dirs_exist_ok=True)
    src_meshes = set(os.listdir(os.path.join(DESC, "meshes")))
    for f in os.listdir(os.path.join(PI_WEB, "meshes")):
        if f.endswith(".stl") and f not in src_meshes:
            os.remove(os.path.join(PI_WEB, "meshes", f))   # stale mesh from an older build
    print("synced ->", PI_WEB)
